async function seed() {
  try {
    // Fetch teacher with pagination
    let teacher = null;
    let page = 1;
    while (true) {
      const { data: usersData, error: usersErr } = await supabaseAdmin.auth.admin.listUsers({ page, perPage: 100 });
      if (usersErr) throw usersErr;
      if (!usersData || usersData.users.length === 0) break;
      
      teacher = usersData.users.find(u => u.email === 'kpk22128@gmail.com');
      if (teacher) break;
      page++;
    }

    if (!teacher) {
      console.log('Teacher kpk22128@gmail.com not found. Aborting.');
      process.exit(1);
    }

    const teacherId = teacher.id;
    console.log('Found teacher:', teacherId);

    // Delete previously incorrectly inserted questions
    console.log('Cleaning up old mistakenly inserted questions...');
    await supabaseAdmin
      .from('questions')
      .delete()
      .eq('subject', 'Hindi')
      .eq('points', 2)
      .eq('time_limit', 2)
      .like('title', '[%');

    const rows = HINDI_COURSE_B_QUESTIONS.map(q => ({
      created_by: teacherId,
      chapter: q.chapter,
      title: `[${q.chapter}] ${q.title}`,
      body: '',
      hint: q.hint,
      explanation: q.explanation,
      subject: 'Hindi',
      class_grade: '10',
      points: 2,
      time_limit: 2,
      difficulty: 'moderate',
      options: q.options,
      correct_option: q.correct,
    }));

    console.log(`Prepared ${rows.length} questions for Course B.`);

    const BATCH = 15;
    let inserted = 0;
    for (let i = 0; i < rows.length; i += BATCH) {
      const batch = rows.slice(i, i + BATCH);
      const { error } = await supabaseAdmin.from('questions').insert(batch);
      if (error) {
        console.error(`Error inserting batch ${Math.floor(i/BATCH)+1}:`, error.message);
      } else {
        inserted += batch.length;
        console.log(`Inserted ${inserted} questions...`);
      }
    }

    console.log(`Successfully seeded ${inserted} high-quality Course B questions!`);
  } catch (e) {
    console.error("Seeding failed:", e);
  }
}

seed();
