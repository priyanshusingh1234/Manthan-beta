export async function GET(req: Request) {
  try {
    const { data: userData, error: userErr } = await supabaseAdmin.auth.admin.listUsers();
    if (userErr) return NextResponse.json({ error: userErr.message }, { status: 500 });

    const teacher = userData.users.find(u => u.email === 'kpk22128@gmail.com');
    if (!teacher) {
      return NextResponse.json({ error: 'Teacher account not found' }, { status: 404 });
    }

    const teacherId = teacher.id;

    const rows = HINDI_QUESTIONS.map((q) => {
      // Encode hint and explanation into the body.
      const bodyContent = `**Hint:** ${q.hint}\n\n**Explanation:** ${q.explanation}`;
      
      return {
        created_by: teacherId,
        title: `[${q.chapter}] ${q.title}`,
        body: bodyContent,
        subject: 'Hindi',
        class_grade: '10',
        points: 2,
        time_limit: 2,
        difficulty: 'moderate',
        type: 'mcq',
        options: q.options,
        correct_option: q.correct,
      };
    });

    const BATCH = 20;
    let inserted = 0;
    const errors: string[] = [];

    for (let i = 0; i < rows.length; i += BATCH) {
      const batch = rows.slice(i, i + BATCH);
      const { error } = await supabaseAdmin.from('questions').insert(batch);
      if (error) {
        errors.push(`Batch ${Math.floor(i/BATCH)+1}: ${error.message}`);
      } else {
        inserted += batch.length;
      }
    }

    return NextResponse.json({
      success: true,
      inserted,
      total: HINDI_QUESTIONS.length,
      errors: errors.length > 0 ? errors : undefined,
    });
  } catch (err: any) {
    return NextResponse.json({ error: err.message }, { status: 500 });
  }
}
